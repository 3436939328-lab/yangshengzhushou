// Rebuild with lunar-javascript 1.7.7 (MIT). All library dates are China Standard Time.
const fs = require('node:fs');
const path = require('node:path');
const { Solar } = require('../.work/tools/node_modules/lunar-javascript');
const names = ['小寒','大寒','立春','雨水','惊蛰','春分','清明','谷雨','立夏','小满','芒种','夏至','小暑','大暑','立秋','处暑','白露','秋分','寒露','霜降','立冬','小雪','大雪','冬至'];
const years = [];
for (let year = 1999; year <= 2101; year++) {
  const terms = Solar.fromYmd(year, 6, 1).getLunar().getJieQiTable();
  years.push(names.map(name => Date.parse(terms[name === '冬至' ? 'DONG_ZHI' : name].toYmdHms().replace(' ', 'T') + '+08:00') / 1000));
}
const output = '// Generated by scripts/generate-solar-terms.cjs from lunar-javascript 1.7.7 (MIT).\n' +
  'export const SOLAR_TERM_START_YEAR: number = 1999;\n' +
  'export const SOLAR_TERM_TIMES: number[][] = [\n' + years.map(row => '  [' + row.join(', ') + ']').join(',\n') + '\n];\n';
fs.writeFileSync(path.resolve(__dirname, '../entry/src/main/ets/utils/SolarTermData.ets'), output);
